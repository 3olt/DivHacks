// The officer service (OFFICER_URL, default :4004): the HUMAN approver's signing seat (Phase 3, builder B).
// It loads ONLY the root .env + xrpl/.env.officer (loadEnv("officer")), holds only OFFICER_SEED (weight 1 of quorum 3 on
// agent_account) and refuses to start if any other *_SEED is in its environment. Each HTTP call marked [HUMAN CLICK] below
// stands for a click by the human officer; it is logged as such.
//
// Click authentication (Phase 3 fixes): every [HUMAN CLICK] route requires the header `x-officer-token` equal to
// OFFICER_CLICK_TOKEN, which exists ONLY in xrpl/.env.officer (generated by `npm run setup:xrpl`; never printed). It is
// compared in constant time. The officer's own click CLI (scripts/officer-click.ts, `npm run officer:click`) loads it; the
// agent processes (xrpl service, demo runner) never do, so they cannot press the officer's buttons over HTTP. A request that
// carries an `Origin` header (i.e. from a browser page) is refused too, and the custom header makes every click a
// non-simple request, so a web page cannot forge one (no CORS is registered).
//
//   GET  /health                       -> {ok, role:"officer", signer_address, agent_account, signer_list, cosigner_url, xrpl_service_url}
//   GET  /approvals                    -> {ok, approvals: PendingApproval[]}  (newest first; the officer's inbox)
//   POST /approvals/:decision_id       [HUMAN CLICK] {amount, destination, decision_hash} = what the officer saw and approves.
//        The officer verifies the pending decision itself (hash recomputed, registry wallet from its own pinned accounts
//        file, contract payee, and the CO-SIGNER's own record of the refusal: GET :4002/over-limit/:decision_id), refuses
//        unless the click's {amount, destination, decision_hash} equal that verified intent, claims it once (single use;
//        expires 24 h after the pending decision), then asks the xrpl service (:4001) to rebuild and execute it.
//        200 {ok, approval_id, decision (the NEW released decision), explorer_url, engine_result} | 400/401/404/409/410/422/502/503
//   POST /approvals/:decision_id/sign  {tx_blob, approval_id}  (called by the xrpl service during that execution, not a click;
//        bound to the approved intent in this process's memory) 200 {ok, signed_blob} only if the tx is EXACTLY the approved
//        payment (fresh, agent-signed); 422 {ok:false, problems}
//   GET  /agent/status                 -> {ok, config: CANONICAL|REVOKED|OTHER, master_disabled, entries, quorum}
//   POST /agent/revoke                 [HUMAN CLICK] kill switch: SignerListSet {cosigner:2, officer:1} q3 (officer + co-signer)
//   POST /agent/restore                [HUMAN CLICK] SignerListSet back to {agent:1, cosigner:2, officer:1} q3 (idempotent)
//        200 {ok, target, changed, before, after, master_disabled, engine_result, final, tx_hash, explorer_url, message}
//   POST /payees/:ein/change-requests/:request_id/resolve {decision:"approve"|"reject", confirm_freeze?}   [HUMAN CLICK]
//        wraps resolvePayeeChange(): signs the resolution with the officer key and delivers it to the co-signer. "approve"
//        needs confirm_freeze: true (in this build an approved change keeps the EIN frozen: re-onboarding is not automated)
//   POST /escrow/milestones/:milestone_id/approve-release   [HUMAN CLICK]   SIMULATED escrow (CTT test token): the officer
//        reads the co-signer's escrow record and the escrow ON-LEDGER, checks the destination is its pinned registry wallet,
//        signs a MilestoneReleaseApproval bound to that escrow and delivers it to the co-signer (POST :4002/escrow/release-approval),
//        which reveals the fulfillment only while it holds such an approval. 200 {ok, approval, escrow, cosigner} | 401/404/409/502
//
// Run: npm run officer   (repo root)
